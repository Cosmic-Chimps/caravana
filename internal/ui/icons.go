// icon is the template function {{icon "house"}} or {{icon "plus" 14}}: the
// named icon as an inline <svg> of the given size in pixels (16 when not
// given), stroke 1.5 as the design draws them. The shapes are our own
// constants, so returning them as template.HTML is safe. An unknown name
// draws nothing; a test checks every name the templates use.
func icon(name string, size ...int) template.HTML {
	shapes, ok := icons[name]
	if !ok {
		return ""
	}
	px := 16
	if len(size) > 0 && size[0] > 0 {
		px = size[0]
	}
	return template.HTML(fmt.Sprintf(`<svg class="cv-icon" xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">%s</svg>`, px, px, shapes))
}
